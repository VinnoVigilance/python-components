"""Database operations for versioned media post-processing results."""

from psycopg2.extras import Json, RealDictCursor


def scan_end(connection, incremental=False):
    """Cap paging at the highest visible ID when the scan begins."""
    table = "delivery.media_daily_delta_actions" if incremental else "core.media_record"
    with connection.cursor() as cursor:
        cursor.execute(f"SELECT COALESCE(MAX(id), 0) FROM {table}")
        return cursor.fetchone()[0]


def find_current_batch(connection, after_id, end_id, batch_size):
    """Read current, non-deleted core versions and their source names."""
    with connection.cursor(cursor_factory=RealDictCursor) as cursor:
        cursor.execute("""
            SELECT m.id, m.vv_media_id, m.version_no, m.media_payload,
                   m.change_type, s.name AS source_name
            FROM core.media_record m
            LEFT JOIN common.lkup_media_source s ON s.id = m.source_id
            WHERE m.id > %s AND m.id <= %s AND m.is_current = TRUE
              AND COALESCE(UPPER(m.change_type), '') <> 'DELETED'
            ORDER BY m.id LIMIT %s
        """, (after_id, end_id, batch_size))
        return [dict(row) for row in cursor.fetchall()]


def latest_result_date(cursor):
    cursor.execute("SELECT MAX(created_at)::date FROM core.media_record_post_process")
    return cursor.fetchone()[0]


def find_delta_batch(connection, effective_date, after_id, end_id, batch_size):
    """Read one effective date's delta actions with their exact core rows.

    Keep missing or mismatched references and DELETE actions visible to the
    caller for reporting; do not silently treat them as successfully processed.
    """
    with connection.cursor(cursor_factory=RealDictCursor) as cursor:
        cursor.execute("""
            SELECT d.id AS delta_id, d.effective_date, d.action,
                   d.vv_media_id AS delta_vv_media_id,
                   d.media_record_id AS delta_media_record_id,
                   m.id, m.vv_media_id, m.version_no, m.media_payload,
                   m.change_type, m.is_current, s.name AS source_name
            FROM delivery.media_daily_delta_actions d
            LEFT JOIN core.media_record m ON m.id = d.media_record_id
            LEFT JOIN common.lkup_media_source s ON s.id = m.source_id
            WHERE d.effective_date = %s AND d.id > %s AND d.id <= %s
            ORDER BY d.id LIMIT %s
        """, (effective_date, after_id, end_id, batch_size))
        return [dict(row) for row in cursor.fetchall()]


def lock_current_source(cursor, record):
    """Lock the exact source version, coordinating with core ingestion."""
    cursor.execute("""
        SELECT id FROM core.media_record
        WHERE id = %s AND vv_media_id = %s AND version_no = %s
          AND is_current = TRUE
          AND COALESCE(UPPER(change_type), '') <> 'DELETED'
        FOR UPDATE
    """, (record["media_record_id"], record["vv_media_id"], record["media_version"]))
    return cursor.fetchone() is not None


def find_current_result(cursor, vv_media_id):
    cursor.execute("""
        SELECT id, post_process_hash, media_version FROM core.media_record_post_process
        WHERE vv_media_id = %s AND is_current = TRUE
        FOR UPDATE
    """, (vv_media_id,))
    rows = cursor.fetchall()
    if len(rows) > 1:
        raise RuntimeError(f"Multiple current post-processing results for vv_media_id {vv_media_id}")
    return rows[0] if rows else None


def lock_delete_source(cursor, record):
    """Lock the referenced core row and reject deletes superseded in core."""
    cursor.execute("""
        SELECT id FROM core.media_record
        WHERE id = %s AND vv_media_id = %s FOR UPDATE
    """, (record["id"], record["vv_media_id"]))
    if cursor.fetchone() is None:
        return False
    cursor.execute("""
        SELECT 1 FROM core.media_record
        WHERE vv_media_id = %s AND is_current = TRUE AND version_no > %s
        LIMIT 1
    """, (record["vv_media_id"], record["version_no"]))
    return cursor.fetchone() is None


def expire_result(cursor, result_id):
    """Close both validity fields; is_current is no longer generated by PostgreSQL."""
    cursor.execute("""
        UPDATE core.media_record_post_process SET is_current = FALSE, to_date = NOW()
        WHERE id = %s AND is_current = TRUE
    """, (result_id,))
    if cursor.rowcount != 1:
        raise RuntimeError(f"Could not expire post-processing result {result_id}")


def insert_result(cursor, record):
    cursor.execute("""
        INSERT INTO core.media_record_post_process
            (media_record_id, vv_media_id, media_version, analysis_payload,
             processor_manifest, post_process_hash, from_date, to_date, is_current)
        VALUES (%s, %s, %s, %s, %s, %s, NOW(), NULL, TRUE)
        RETURNING id
    """, (record["media_record_id"], record["vv_media_id"], record["media_version"],
          Json(record["analysis_payload"]), Json(record["processor_manifest"]),
          record["post_process_hash"]))
    return cursor.fetchone()[0]
